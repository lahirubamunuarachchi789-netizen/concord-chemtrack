-- ============================================================
--  Concord ChemTrack - Supabase schema
--  Run once in: Supabase Dashboard -> SQL Editor -> New query
--  (The app only manages data; tables are created here.)
-- ============================================================

-- ------------------------------------------------------------ users
-- Expected to already exist. Shown for reference / fresh installs.
create table if not exists public.users (
    id         uuid primary key default gen_random_uuid(),
    username   text not null unique,
    password   text not null,               -- pbkdf2_sha256 hash
    created_at timestamptz not null default now()
);

-- ------------------------------------------------- chemical categories
create table if not exists public.chemical_categories (
    id         bigint generated by default as identity primary key,
    name       text not null unique,
    created_at timestamptz not null default now()
);

-- ---------------------------------------------------- chemical items
create table if not exists public.chemical_items (
    id            bigint generated by default as identity primary key,
    item_code     text not null unique,
    name          text not null,
    category      text,
    unit          text not null default 'kg',
    supplier      text,
    reorder_level numeric(14,3) not null default 0,
    opening_qty   numeric(14,3) not null default 0,
    notes         text,
    created_by    text,
    created_at    timestamptz not null default now()
);

create index if not exists idx_chemical_items_name on public.chemical_items (name);

-- ------------------------------------------------ stock transactions
create table if not exists public.stock_transactions (
    id         bigint generated by default as identity primary key,
    item_id    bigint not null references public.chemical_items(id) on delete cascade,
    txn_type   text not null check (txn_type in ('IN','OUT','ADJUST')),
    quantity   numeric(14,3) not null check (quantity > 0),
    unit       text,
    batch_no   text,
    supplier   text,
    issued_to  text,
    reference  text,
    remarks    text,
    txn_date   date not null default current_date,
    created_by text,
    created_at timestamptz not null default now()
);

create index if not exists idx_txn_item   on public.stock_transactions (item_id);
create index if not exists idx_txn_date   on public.stock_transactions (txn_date desc);
create index if not exists idx_txn_type   on public.stock_transactions (txn_type);

-- ------------------------------------------------------------- access
-- The app is used by authenticated staff through the sidebar login, with a
-- trusted server-side key. If you expose it publicly, switch on RLS and add
-- policies instead of leaving these tables open.
alter table public.chemical_items     enable row level security;
alter table public.stock_transactions enable row level security;
alter table public.chemical_categories enable row level security;

